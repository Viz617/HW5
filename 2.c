#include <stdio.h>

int main(void)
{
    /*Сначала внешний цикл берет цифру 1, а внутрений прогоняет 5 значений, как только внутрений закончился
    внешний меняет цифру 1 на цифру 2 и так до 5*/
    for (int n = 1; n <= 5; n++){
        for (int m = 1; m <= 5; m++){
            printf("%d\t",n*m);
        }
        printf("\n");
    }
    return 0;
}